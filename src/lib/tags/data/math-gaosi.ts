type Curriculum = Record<string, Array<{ chapter: string; sections: Array<{ section: string; tags: string[] }> }>>;

/**
 * 在小学各年级末尾追加「课外拓展（高思）」章节；与该年级课内知识点同名的不再重复添加
 */
export function withGaosiExtension(curriculum: Curriculum): Curriculum {
    const result: Curriculum = { ...curriculum };
    for (const [grade, { upper, lower }] of Object.entries(MATH_GAOSI_EXTENSION)) {
        const chapters = curriculum[grade] || [];
        const schoolTags = new Set(chapters.flatMap((chapter) => chapter.sections.flatMap((section) => section.tags)));
        const fresh = (tags: string[]) => tags.filter((tag) => !schoolTags.has(tag));
        result[grade] = [
            ...chapters,
            {
                chapter: GAOSI_CHAPTER_NAME,
                sections: [
                    { section: '高思上册', tags: fresh(upper) },
                    { section: '高思下册', tags: fresh(lower) },
                ],
            },
        ];
    }
    return result;
}
