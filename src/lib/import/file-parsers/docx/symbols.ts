const FONT_TABLES: Array<{ prefix: string; table: Record<number, string> }> = [
    { prefix: "wingdings", table: WINGDINGS_MAP },
    { prefix: "symbol", table: SYMBOL_MAP },
];

/**
 * 尽力把 w:sym 的（字体, 字符码）映射为可读字符。
 * 未识别时返回 "[符号]" 占位。
 */
export function mapSymChar(font: string, charCode: number): string {
    const normalizedFont = font.trim().toLowerCase();
    for (const { prefix, table } of FONT_TABLES) {
        if (!normalizedFont.startsWith(prefix)) continue;
        const mapped = table[charCode];
        if (mapped !== undefined) return mapped;
    }
    return "[符号]";
}
